-- Flyway migration: V1__init_schema.sql
-- PostgreSQL version of the original MySQL bookstore schema.
-- Database creation/USE statements are intentionally omitted because Flyway
-- connects to the target database before running this migration.

-- 1. PHÂN QUYỀN & NGƯỜI DÙNG
CREATE TABLE app_role
(
    role_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_user
(
    user_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id      BIGINT       NOT NULL,
    username     VARCHAR(50)  NOT NULL UNIQUE,
    password     VARCHAR(255) NOT NULL,
    email        VARCHAR(100),
    phone        VARCHAR(20),
    address      VARCHAR(255),
    full_name    VARCHAR(100),
    total_points INT       DEFAULT 0 CHECK (total_points >= 0),
    status       INT   DEFAULT 1,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (role_id) REFERENCES app_role (role_id)
);

-- 2. DANH MỤC & ĐỐI TÁC
CREATE TABLE category
(
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       NULL,
    name        VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (parent_id) REFERENCES category (category_id)
);

CREATE TABLE author
(
    author_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    biography  TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE publisher
(
    publisher_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    contact_email VARCHAR(100),
    phone         VARCHAR(20),
    address       VARCHAR(255),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE supplier
(
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    phone       VARCHAR(20),
    address     VARCHAR(255),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. THÔNG TIN SÁCH & VẬT PHẨM
CREATE TABLE book
(
    book_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_id     BIGINT,
    title            VARCHAR(255) NOT NULL,
    publication_year INT,
    language         VARCHAR(50),
    original_price   DECIMAL(15, 2) CHECK (original_price >= 0),
    selling_price    DECIMAL(15, 2) CHECK (selling_price >= 0),
    total_stock      INT       DEFAULT 0 CHECK (total_stock >= 0),
    description      TEXT,
    cover_image      VARCHAR(255),
    status           INT   DEFAULT 1,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (publisher_id) REFERENCES publisher (publisher_id)
);

CREATE TABLE book_item
(
    book_item_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id              BIGINT NOT NULL,
    barcode              VARCHAR(100) UNIQUE,
    condition_type       VARCHAR(50),
    condition_note       TEXT,
    deposit_amount       DECIMAL(15, 2) CHECK (deposit_amount >= 0),
    current_rental_price DECIMAL(15, 2) CHECK (current_rental_price >= 0),
    is_for_rent          INT   DEFAULT 0,
    status               VARCHAR(50),
    position             VARCHAR(100),
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (book_id) REFERENCES book (book_id)
);

CREATE TABLE book_author
(
    book_id     BIGINT NOT NULL,
    author_id   BIGINT NOT NULL,
    author_role VARCHAR(100),
    PRIMARY KEY (book_id, author_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id),
    FOREIGN KEY (author_id) REFERENCES author (author_id)
);

CREATE TABLE book_category
(
    book_id     BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    is_primary  INT DEFAULT 0,
    PRIMARY KEY (book_id, category_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id),
    FOREIGN KEY (category_id) REFERENCES category (category_id)
);

-- 4. HỆ THỐNG FLASH SALE
CREATE TABLE flash_sale_campaign
(
    campaign_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    start_time  TIMESTAMP     NOT NULL,
    end_time    TIMESTAMP     NOT NULL,
    status      VARCHAR(20) DEFAULT 'UPCOMING',
    created_at  TIMESTAMP   DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE flash_sale_item
(
    flash_sale_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id        BIGINT         NOT NULL,
    book_id            BIGINT         NOT NULL,
    flash_sale_price   DECIMAL(15, 2) NOT NULL,
    quantity           INT            NOT NULL,
    sold_quantity      INT DEFAULT 0,
    max_per_user       INT DEFAULT 1,
    FOREIGN KEY (campaign_id) REFERENCES flash_sale_campaign (campaign_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id)
);

-- 5. GIỎ HÀNG & KHUYẾN MÃI
CREATE TABLE promotion
(
    promotion_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(50) NOT NULL UNIQUE,
    discount_percent    DECIMAL(5, 2) CHECK (discount_percent >= 0 AND discount_percent <= 100),
    max_discount_amount DECIMAL(15, 2) CHECK (max_discount_amount >= 0),
    min_order_value     DECIMAL(15, 2) CHECK (min_order_value >= 0),
    usage_limit         INT         NULL CHECK (usage_limit > 0),
    used_count          INT       DEFAULT 0 CHECK (used_count >= 0),
    start_date          TIMESTAMP,
    end_date            TIMESTAMP,
    status              INT   DEFAULT 1,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cart
(
    cart_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

CREATE TABLE cart_item
(
    cart_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id      BIGINT NOT NULL,
    book_id      BIGINT NOT NULL,
    quantity     INT    NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at   TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cart_id) REFERENCES cart (cart_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id)
);

-- 6. ĐƠN HÀNG & CHI TIẾT ĐƠN HÀNG
CREATE TABLE orders
(
    order_id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   BIGINT NOT NULL,
    promotion_id              BIGINT NULL,
    points_used               INT            DEFAULT 0 CHECK (points_used >= 0),
    promotion_discount_amount DECIMAL(15, 2) DEFAULT 0 CHECK (promotion_discount_amount >= 0),
    point_discount_amount     DECIMAL(15, 2) DEFAULT 0 CHECK (point_discount_amount >= 0),
    total_amount              DECIMAL(15, 2) CHECK (total_amount >= 0),
    shipping_address          TEXT,
    payment_method            VARCHAR(50),
    payment_status            VARCHAR(50),
    order_status              VARCHAR(50),
    created_at                TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    FOREIGN KEY (promotion_id) REFERENCES promotion (promotion_id)
);

CREATE TABLE order_detail
(
    order_detail_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT NOT NULL,
    book_id            BIGINT NOT NULL,
    flash_sale_item_id BIGINT NULL,
    quantity           INT    NOT NULL CHECK (quantity > 0),
    unit_price         DECIMAL(15, 2) CHECK (unit_price >= 0),
    FOREIGN KEY (order_id) REFERENCES orders (order_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id),
    FOREIGN KEY (flash_sale_item_id) REFERENCES flash_sale_item (flash_sale_item_id)
);

-- 7. QUẢN LÝ THUÊ SÁCH
CREATE TABLE rental
(
    rental_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT   NOT NULL,
    book_item_id   BIGINT   NOT NULL,
    rent_date      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    due_date       TIMESTAMP NOT NULL,
    return_date    TIMESTAMP NULL,
    actual_deposit DECIMAL(15, 2) CHECK (actual_deposit >= 0),
    rental_fee     DECIMAL(15, 2) CHECK (rental_fee >= 0),
    penalty_fee    DECIMAL(15, 2) DEFAULT 0 CHECK (penalty_fee >= 0),
    payment_method VARCHAR(50),
    payment_status VARCHAR(50),
    status         VARCHAR(50),
    created_at     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    FOREIGN KEY (book_item_id) REFERENCES book_item (book_item_id)
);

-- 8. NHẬP HÀNG & KHO VẬT LÝ
CREATE TABLE book_import
(
    import_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    import_date TIMESTAMP  DEFAULT CURRENT_TIMESTAMP,
    total_cost  DECIMAL(15, 2) CHECK (total_cost >= 0),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (supplier_id) REFERENCES supplier (supplier_id),
    FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

CREATE TABLE import_detail
(
    import_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id        BIGINT NOT NULL,
    book_id          BIGINT NOT NULL,
    quantity         INT    NOT NULL CHECK (quantity > 0),
    import_price     DECIMAL(15, 2) CHECK (import_price >= 0),
    FOREIGN KEY (import_id) REFERENCES book_import (import_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id)
);

CREATE TABLE inventory_log
(
    log_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    book_item_id        BIGINT NOT NULL,
    action_type         VARCHAR(50),
    reference_order_id  BIGINT NULL,
    reference_import_id BIGINT NULL,
    reference_rental_id BIGINT NULL,
    note                TEXT,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    FOREIGN KEY (book_item_id) REFERENCES book_item (book_item_id),
    FOREIGN KEY (reference_order_id) REFERENCES orders (order_id),
    FOREIGN KEY (reference_import_id) REFERENCES book_import (import_id),
    FOREIGN KEY (reference_rental_id) REFERENCES rental (rental_id)
);

-- 9. LỊCH SỬ ĐIỂM, ĐÁNH GIÁ & THANH TOÁN
CREATE TABLE point_transaction
(
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL,
    order_id       BIGINT NULL,
    rental_id      BIGINT NULL,
    points_changed INT    NOT NULL,
    reason         VARCHAR(255),
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    FOREIGN KEY (order_id) REFERENCES orders (order_id),
    FOREIGN KEY (rental_id) REFERENCES rental (rental_id)
);

CREATE TABLE review
(
    review_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL,
    book_id     BIGINT  NOT NULL,
    rating      INT NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment     TEXT,
    is_approved INT   DEFAULT 0,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    FOREIGN KEY (book_id) REFERENCES book (book_id)
);

CREATE TABLE payment_transaction
(
    payment_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT         NOT NULL,
    provider                VARCHAR(50)    NOT NULL,
    provider_transaction_id VARCHAR(100),
    amount                  DECIMAL(15, 2) NOT NULL CHECK (amount >= 0),
    status                  VARCHAR(50)    NOT NULL,
    response_code           VARCHAR(50),
    created_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (order_id) REFERENCES orders (order_id)
);

-- 10. HỆ THỐNG CHATBOT
CREATE TABLE chat_session
(
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NULL,
    started_at TIMESTAMP   DEFAULT CURRENT_TIMESTAMP,
    ended_at   TIMESTAMP NULL,
    status     VARCHAR(50) DEFAULT 'ACTIVE',
    FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

CREATE TABLE chat_message
(
    message_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT      NOT NULL,
    sender_type VARCHAR(20) NOT NULL,
    content     TEXT        NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (session_id) REFERENCES chat_session (session_id)
);

